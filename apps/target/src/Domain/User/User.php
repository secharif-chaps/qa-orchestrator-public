<?php

declare(strict_types=1);

namespace App\Domain\User;

use ApiPlatform\Metadata\ApiFilter;
use ApiPlatform\Metadata\ApiProperty;
use ApiPlatform\Metadata\ApiResource;
use ApiPlatform\Metadata\GetCollection;
use ApiPlatform\OpenApi\Model\Operation;
use ApiPlatform\OpenApi\Model\Parameter;
use App\Domain\Organisation\OrganisationUser;
use App\Domain\WatchFile\WatchFile;
use App\Domain\WatchFile\WatchFileUser;
use App\Domain\WatchFileActivity\WatchFileActivity;
use App\Infrastructure\User\ApiFilter\ExcludeCurrentUserFilter;
use App\Infrastructure\User\ApiFilter\ExcludeWatchFileSharedUsersFilter;
use App\Infrastructure\User\ApiFilter\UserMultiFieldSearchFilter;
use Doctrine\Common\Collections\ArrayCollection;
use Doctrine\Common\Collections\Collection;
use Doctrine\ORM\Mapping as ORM;
use Symfony\Bridge\Doctrine\Types\UuidType;
use Symfony\Component\Security\Core\User\UserInterface;
use Symfony\Component\Serializer\Annotation\Groups;
use Symfony\Component\String\UnicodeString;

#[ORM\Entity]
#[ORM\Table(name: '`user`')]
#[ApiResource(
    operations: [
        new GetCollection(
            paginationEnabled: true,
            openapi: new Operation(
                summary: 'Get a list of users',
                description: <<<'EOT'
                    Retrieve a paginated list of users. This endpoint is typically used for user search and selection features, such as sharing watch files with other users.

                    Available filters:
                    - search (string): Search users by email, first name, last name, or display name. Minimum 2 characters required.
                    - excludeCurrentUser (boolean): When true, excludes the currently authenticated user from results. Default: false.
                    - excludeWatchFileSharedUsers (UUID): Excludes users who already have access to the specified watch file.

                    Response:
                    - Returns a paginated list of user objects with basic profile information
                    - Each user includes: id, email, firstName, lastName, displayName, defaultThumbnail
                    EOT
                ,
                parameters: [
                    new Parameter(
                        name: 'search',
                        in: 'query',
                        description: 'Search term to filter users by email, first name, last name, or display name (minimum 2 characters)',
                        required: false,
                        schema: [
                            'type' => 'string',
                            'minLength' => 2,
                        ],
                        example: 'john',
                    ),
                    new Parameter(
                        name: 'excludeCurrentUser',
                        in: 'query',
                        description: 'Exclude the currently authenticated user from results',
                        required: false,
                        schema: [
                            'type' => 'boolean',
                            'default' => false,
                        ],
                    ),
                    new Parameter(
                        name: 'excludeWatchFileSharedUsers',
                        in: 'query',
                        description: 'Exclude users who already have access to the specified watch file (provide watch file UUID)',
                        required: false,
                        schema: [
                            'type' => 'string',
                            'format' => 'uuid',
                        ],
                    ),
                ],
            ),
        ),
    ],
    normalizationContext: [
        'groups' => ['watch_file:read'],
    ]
)]
#[ApiFilter(UserMultiFieldSearchFilter::class)]
#[ApiFilter(ExcludeCurrentUserFilter::class)]
#[ApiFilter(ExcludeWatchFileSharedUsersFilter::class)]
class User implements UserInterface
{
    public const string ROLE_USER = 'ROLE_USER';

    #[ORM\Id]
    #[ORM\Column(type: UuidType::NAME, unique: true)]
    #[ApiProperty(
        description: 'The unique identifier for the user, typically a UUID.',
        identifier: true,
        example: '123e4567-e89b-12d3-a456-426614174000'
    )]
    #[Groups(['watch_file:read', 'watch_file_user:read', 'watch_file_activity:read', 'document:save'])]
    /**
     * @var non-empty-string|null
     *                            The unique identifier for the user, typically a UUID.
     *                            This UUID is provided by the AuthProvider (Keycloak, etc.), it's not generated by the application.
     */
    private ?string $id = null;

    /**
     * @var non-empty-string|null
     */
    #[ORM\Column(type: 'string', unique: true, nullable: true)]
    #[ApiProperty(
        description: 'The email address of the user, which is unique and used for authentication.',
        example: 'example@chapsvision.com',
        openapiContext: [
            'type' => 'string',
            'format' => 'email',
        ],
    )]
    #[Groups(['watch_file:read', 'watch_file_user:read', 'watch_file_activity:read'])]
    private ?string $email = null;

    /**
     * @var list<string> The user roles
     */
    #[ORM\Column]
    private array $roles = [];

    #[ORM\Column(type: 'string', nullable: false)]
    private string $userName;

    #[ORM\Column(type: 'string', nullable: true)]
    #[Groups(['watch_file:read', 'watch_file_user:read'])]
    private ?string $firstName = null;

    #[ORM\Column(type: 'string', nullable: true)]
    #[Groups(['watch_file:read', 'watch_file_user:read'])]
    private ?string $lastName = null;

    /**
     * @var Collection<int, OrganisationUser>
     */
    #[ORM\OneToMany(targetEntity: OrganisationUser::class, mappedBy: 'user')]
    private Collection $organisationUsers;

    /**
     * @var Collection<int, WatchFile>
     */
    #[ORM\OneToMany(targetEntity: WatchFile::class, mappedBy: 'createdBy')]
    private Collection $watchFiles;

    /**
     * @var Collection<int, WatchFileActivity>
     */
    #[ORM\OneToMany(targetEntity: WatchFileActivity::class, mappedBy: 'user')]
    private Collection $watchFileActivities;

    /**
     * @var Collection<int, WatchFileUser>
     */
    #[ORM\OneToMany(targetEntity: WatchFileUser::class, mappedBy: 'user')]
    private Collection $watchFileUsers;

    /**
     * @var Collection<int, UserFavoriteWatchFile>
     */
    #[ORM\OneToMany(targetEntity: UserFavoriteWatchFile::class, mappedBy: 'user')]
    private Collection $watchFileFavorites;

    /**
     * @param non-empty-string|null $email
     * @param list<string>          $roles
     */
    public function __construct(
        ?string $id = null,
        ?string $email = null,
        array $roles = [],
        string $userName = '',
        ?string $firstName = null,
        ?string $lastName = null,
    ) {
        $this->id = $id;
        $this->email = $email;
        $this->roles = $roles;
        $this->userName = $userName;
        $this->firstName = $firstName;
        $this->lastName = $lastName;
        $this->organisationUsers = new ArrayCollection();
        $this->watchFiles = new ArrayCollection();
        $this->watchFileActivities = new ArrayCollection();
        $this->watchFileUsers = new ArrayCollection();
        $this->watchFileFavorites = new ArrayCollection();
    }

    public function getId(): ?string
    {
        return $this->id;
    }

    /**
     * @return non-empty-string|null
     */
    public function getEmail(): ?string
    {
        return $this->email;
    }

    /**
     * @param non-empty-string $email
     */
    public function setEmail(string $email): self
    {
        $this->email = $email;

        return $this;
    }

    /**
     * A visual identifier that represents this user.
     *
     * @see UserInterface
     */
    public function getUserIdentifier(): string
    {
        $email = $this->getEmail();
        if (null === $email) {
            throw new \LogicException('Email is not set.');
        }

        if ('' === $email) {
            throw new \LogicException('Email is empty.');
        }

        return $email;
    }

    /**
     * @return list<string>
     *
     * @see UserInterface
     */
    public function getRoles(): array
    {
        $roles = $this->roles;

        // guarantee every user at least has ROLE_USER
        if (!\in_array(self::ROLE_USER, $roles, true)) {
            $roles[] = self::ROLE_USER;
        }

        return array_values(array_unique($roles));
    }

    /**
     * @return Collection<int, OrganisationUser>
     */
    public function getOrganisationUsers(): Collection
    {
        return $this->organisationUsers;
    }

    /**
     * @return Collection<int, WatchFile>
     */
    public function getWatchFiles(): Collection
    {
        return $this->watchFiles;
    }

    public function addWatchFile(WatchFile $watchFile): self
    {
        if (!$this->watchFiles->contains($watchFile)) {
            $this->watchFiles->add($watchFile);
            $watchFile->setCreatedBy($this);
        }

        return $this;
    }

    /**
     * @return Collection<int, WatchFileActivity>
     */
    public function getWatchFileActivities(): Collection
    {
        return $this->watchFileActivities;
    }

    /**
     * @see UserInterface
     */
    #[\Deprecated]
    public function eraseCredentials(): void
    {
        // If you store any temporary, sensitive data on the user, clear it here
    }

    public function getUserName(): string
    {
        return $this->userName;
    }

    public function setUserName(string $userName): self
    {
        $this->userName = $userName;

        return $this;
    }

    public function getFirstName(): ?string
    {
        return $this->firstName;
    }

    public function setFirstName(?string $firstName): self
    {
        $this->firstName = $firstName;

        return $this;
    }

    public function getLastName(): ?string
    {
        return $this->lastName;
    }

    public function setLastName(?string $lastName): self
    {
        $this->lastName = $lastName;

        return $this;
    }

    #[Groups([
        'watch_file:read',
        'watch_file_user:read',
        'document:read',
        'grouped_source_activity:read',
        'watch_file_activity:read',
    ])]
    public function getDisplayName(): string
    {
        if ($this->getFirstName() && $this->getLastName()) {
            return new UnicodeString(' ')
                ->join([
                    new UnicodeString($this->getFirstName())
                        ->trim(),
                    new UnicodeString($this->getLastName())
                        ->trim(),
                ])
                ->trim()
                ->lower()
                ->title(true)
                ->toString()
            ;
        }

        return $this->getUserName();
    }

    #[Groups(['watch_file:read', 'watch_file_user:read', 'message:read', 'document:read'])]
    public function getDefaultThumbnail(): string
    {
        $splitName = new ArrayCollection(
            new UnicodeString($this->getDisplayName())
                ->trim()
                ->split('/\s+/', flags: \PREG_SPLIT_NO_EMPTY)
        );

        if (1 === $splitName->count()) {
            // If there's only one word, use the first letter of that word
            /** @var UnicodeString $firstWord */
            $firstWord = $splitName->first();

            return $firstWord->slice(0, 1)
                ->upper()
                ->toString()
            ;
        }

        return $splitName
            ->filter(static fn (UnicodeString $word) => !$word->isEmpty())
            ->reduce(
                static function (UnicodeString $initials, UnicodeString $word) {
                    return $initials->length() >= 2
                        ? $initials
                        : $initials->append($word->slice(0, 1)->toString());
                },
                new UnicodeString(''),
            )
            ->upper()
            ->toString()
        ;
    }

    /**
     * @return Collection<int, WatchFileUser>
     */
    public function getWatchFileUsers(): Collection
    {
        return $this->watchFileUsers;
    }

    public function addWatchFileUser(WatchFileUser $watchFileUser): self
    {
        if (!$this->watchFileUsers->contains($watchFileUser)) {
            $this->watchFileUsers->add($watchFileUser);
            $watchFileUser->setUser($this);
        }

        return $this;
    }

    /**
     * @return Collection<int, UserFavoriteWatchFile>
     */
    public function getWatchFileFavorites(): Collection
    {
        return $this->watchFileFavorites;
    }

    public function addWatchFileFavorites(UserFavoriteWatchFile $watchFileFavorites): self
    {
        if (!$this->watchFileFavorites->contains($watchFileFavorites)) {
            $this->watchFileFavorites->add($watchFileFavorites);
            $watchFileFavorites->setUser($this);
        }

        return $this;
    }
}
